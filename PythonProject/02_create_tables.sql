  "nights" INTEGER NOT NULL,
  "total_price" DOUBLE PRECISION NOT NULL,
  "created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  "payment_status" VARCHAR(20) DEFAULT 'pending',
