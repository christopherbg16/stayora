  "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "room_id" INTEGER NOT NULL,
  "guest" VARCHAR(255) NOT NULL,
  "user_id" INTEGER DEFAULT NULL,
  "start_date" DATE NOT NULL,
